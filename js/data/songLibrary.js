const entry = (value, category, difficulty) => {
  const [title, artist, originalKey] = value.split("|");
  return {
    title,
    artist,
    originalKey,
    chords: "",
    difficulty,
    category,
    sourceUrl: `https://www.ultimate-guitar.com/search.php?search_type=title&value=${encodeURIComponent(title)}`,
    lyricStatus: "Use an authorized source or your own arrangement"
  };
};

